"""Interactive REPL mode for multi-turn sessions with Sidewinder Coding Assistant."""

from __future__ import annotations

import logging
import shutil
import sys
from typing import TYPE_CHECKING

from prompt_toolkit.completion import WordCompleter
from prompt_toolkit.formatted_text import HTML
from prompt_toolkit.history import InMemoryHistory
from prompt_toolkit.key_binding import KeyBindings
from prompt_toolkit.shortcuts import PromptSession

from coder_agent import __version__
from coder_agent.agent import Agent
from coder_agent.commands import SlashCommandHandler
from coder_agent.compactor import estimate_message_tokens
from coder_agent.types import TokenUsage

if TYPE_CHECKING:
    from coder_agent.config import Config
    from coder_agent.context import ContextBuilder
    from coder_agent.providers.base import LLMProvider
    from coder_agent.safety import SafetyGuard
    from coder_agent.tools import ToolRegistry
    from coder_agent.ui import UI


class InteractiveInputSession:
    """Antigravity CLI-style bordered input box powered by prompt_toolkit."""

    SLASH_COMMANDS: dict[str, str] = {
        "/help": "Display guidance on all slash commands",
        "/diff": "Display git diff of changes made during session",
        "/undo": "Rollback workspace to pre-task checkpoint",
        "/commit": "Safely commit changes to Git",
        "/compact": "Compact message history into milestones",
        "/cost": "Display token usage metrics and USD cost",
        "/model": "Inspect active model or switch on the fly",
        "/phase": "Display last task Plan->Act->Validate phase history",
        "/plan": "Display last structured plan generated by agent",
        "/reasoning": "Inspect or set reasoning mode (auto/always/never)",
        "/history": "Display last 10 conversation turns",
        "/reset": "Reset conversation history",
        "/config": "Display active agent configuration",
        "/clear": "Clear terminal screen",
        "/exit": "Exit interactive session",
        "/quit": "Exit interactive session",
    }

    def __init__(self, ui: UI | None = None) -> None:
        self.ui = ui
        self.history = InMemoryHistory()
        self.completer = WordCompleter(
            list(self.SLASH_COMMANDS.keys()),
            meta_dict=self.SLASH_COMMANDS,
            ignore_case=True,
            match_middle=False,
            WORD=True,
        )
        self._kb = self._build_keybindings()
        self.session: PromptSession = PromptSession(
            key_bindings=self._kb,
            completer=self.completer,
            history=self.history,
            multiline=True,
        )

    def _build_keybindings(self) -> KeyBindings:
        kb = KeyBindings()

        @kb.add("enter")
        def _(event):
            """Enter submits the input buffer."""
            event.current_buffer.validate_and_handle()

        @kb.add("escape", "enter")
        @kb.add("c-j")
        def _(event):
            """Alt+Enter, Esc+Enter, or Ctrl+J inserts a newline."""
            event.current_buffer.insert_text("\n")

        return kb

    def prompt(self, token_count: int = 0) -> str:
        """Prompt user with a bordered text box and return accumulated string."""
        if not sys.stdin.isatty():
            # Graceful fallback for non-TTY streams, pipes, and automated test runners
            try:
                first_line = input()
            except EOFError:
                raise
            stripped = first_line.strip()
            if not stripped or stripped.startswith("/"):
                return stripped

            lines = [first_line]
            while True:
                try:
                    next_line = input()
                except EOFError:
                    break
                if next_line == "":
                    break
                lines.append(next_line)
            return "\n".join(lines).strip()

        # Dynamic responsive border width
        cols = min(shutil.get_terminal_size((80, 24)).columns - 2, 78)
        cols = max(cols, 40)
        header_title = " Requirement / Message "
        token_badge = f" [{token_count:,} tok] " if token_count > 0 else " "
        dashes_len = max(4, cols - len(header_title) - len(token_badge) - 2)
        top_dashes = "─" * dashes_len
        bottom_dashes = "─" * (cols + 2)

        box_top = (
            f"<ansibrightblack>╭─</ansibrightblack>"
            f"<ansicyan><b>{header_title}</b></ansicyan>"
            f"<ansibrightblack>{top_dashes}</ansibrightblack>"
            f"<ansiyellow>{token_badge}</ansiyellow>"
            f"<ansibrightblack>╮</ansibrightblack>\n"
            f"<ansibrightblack>│</ansibrightblack> <ansigreen>❯</ansigreen> "
        )

        def continuation(width: int, line_number: int, is_soft_wrap: bool) -> HTML:
            return HTML("<ansibrightblack>│  </ansibrightblack>")

        bottom_bar = HTML(
            f"<ansibrightblack>╰{bottom_dashes}╯</ansibrightblack>\n"
            " <ansidim><b>[Enter]</b> Send   "
            "<b>[Alt+Enter]</b> Line Break   "
            "<b>[/]</b> Commands   "
            "<b>[Ctrl+C]</b> Cancel</ansidim>"
        )

        try:
            return self.session.prompt(
                HTML(box_top),
                prompt_continuation=continuation,
                bottom_toolbar=bottom_bar,
            ).strip()
        except KeyboardInterrupt:
            raise


def read_multiline_input(prompt_str: str = "", ui: UI | None = None) -> str:
    """Read input from the interactive text box or non-TTY fallback."""
    if ui is None:
        from coder_agent.ui import UI
        ui = UI()
    session = InteractiveInputSession(ui)
    return session.prompt()


def start_interactive(
    config: Config,
    provider: LLMProvider,
    tools: ToolRegistry,
    context: ContextBuilder,
    safety: SafetyGuard,
    ui: UI,
    logger: logging.Logger,
    session_id: str | None = None,
) -> int:
    """Launch the interactive REPL loop with conversation continuity and signal trapping."""
    title_str = f"Sidewinder Coding Assistant v{__version__}"
    padding = " " * max(0, 54 - len(title_str))
    banner = f"""
{ui.bold('┌────────────────────────────────────────────────────────┐')}
{ui.bold('│')}  {ui.cyan('Sidewinder Coding Assistant')} v{__version__}{padding}{ui.bold('│')}
{ui.bold('├────────────────────────────────────────────────────────┤')}
{ui.bold('│')}  Provider:    {ui.green(provider.name.ljust(40))} {ui.bold('│')}
{ui.bold('│')}  Project Dir: {ui.yellow(config.project_dir[:40].ljust(40))} {ui.bold('│')}
{ui.bold('│')}  Approval:    {config.approval_mode.ljust(40)} {ui.bold('│')}
{ui.bold('└────────────────────────────────────────────────────────┘')}
Type a coding request, {ui.cyan('/help')} for commands, or {ui.cyan('/exit')} to quit.
"""
    print(banner)

    # Maintain single persistent Agent instance across REPL turns for conversational continuity
    agent = Agent(
        provider=provider,
        tools=tools,
        context=context,
        safety=safety,
        config=config,
        ui=ui,
        logger=logger,
        session_id=session_id,
    )

    if session_id:
        prior_messages = agent.storage.get_session_messages(agent.session_id)
        if prior_messages:
            agent.messages = prior_messages
            ui.info(f"Resumed session {ui.bold(agent.session_id)} ({len(prior_messages)} messages loaded)")

    cumulative_tokens = TokenUsage()
    last_checkpoint_id: str | None = None
    interrupted_once = False
    cmd_handler = SlashCommandHandler(agent=agent, ui=ui, config=config)
    input_session = InteractiveInputSession(ui)

    while True:
        try:
            tokens_in_history = estimate_message_tokens(agent.messages)
            user_input = input_session.prompt(token_count=tokens_in_history)
            interrupted_once = False
        except KeyboardInterrupt:
            if interrupted_once:
                print("\nExiting session.")
                break
            interrupted_once = True
            print(f"\n{ui.dim('Press Ctrl+C again or type /exit to quit.')}")
            continue
        except EOFError:
            print("\nExiting session.")
            break

        if not user_input:
            continue

        # Handle slash commands via dedicated handler
        cmd_result = cmd_handler.handle(user_input, cumulative_tokens, last_checkpoint_id)
        if cmd_result.handled:
            if cmd_result.should_exit:
                break
            if cmd_result.new_checkpoint_id is not None:
                last_checkpoint_id = cmd_result.new_checkpoint_id
            continue

        # Execute coding requirement
        try:
            result = agent.run(user_input)
            cumulative_tokens.add(result.total_tokens)
            if result.checkpoint_id:
                last_checkpoint_id = result.checkpoint_id
        except KeyboardInterrupt:
            ui.warning("\n[Task interrupted by user (Ctrl+C). Returning to prompt.]")
        except Exception as e:
            ui.error(f"Task failed with error: {e}")
            logger.exception("Error executing interactive task")

        print()

    return 0
